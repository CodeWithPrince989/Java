public class L_Loops {
    public static void main(String[] a) {
        //For Loop
        for(int i=0; i<10; i++){
            System.out.println("My Name Is Prince");
        }

        //While Loop
        int n = 18;
        while (n>10) {
            System.out.println("Hello, How are You");
            n-=1;
        }

        //Do-While Loop
        do {
            System.out.println("Kaise hai Aap Log");
            n-=1;
        }
        while (n>10);
    }
}
